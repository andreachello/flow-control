//! Render the flow document: one file per flow, plus the slice table, the ledger and an index.
//! Output is plain quoted YAML written by hand so the bytes are stable and diffs stay small.

use crate::flows::Flow;
use crate::parse::{Role, SUPPORT};
use crate::repo::{Graph, Repo, SRef};
use crate::util::{fnv64, q, qlist, ranges};
use std::collections::{BTreeMap, HashMap};
use std::fmt::Write;

pub const HEADER: &str = "# Generated by `flow lift`. Do not edit: change the code or flow.toml and lift again.\n";

#[derive(Default)]
pub struct Lifted {
    pub files: BTreeMap<String, String>,
    pub fingerprint: String,
    pub stats: Stats,
}

#[derive(Default)]
pub struct Stats {
    pub files: usize,
    pub lines: usize,
    pub slices: usize,
    pub flows: usize,
    pub placed_by_hand: usize,
    pub unplaced: Vec<(String, usize, String, String)>,
    pub unresolved: Vec<(String, usize, String, String)>,
    pub loose: Vec<String>,
    pub broken_round_trip: Vec<String>,
    pub parse_errors: Vec<String>,
}

pub fn used_by(flows: &[Flow]) -> HashMap<SRef, Vec<usize>> {
    let mut m: HashMap<SRef, Vec<usize>> = HashMap::new();
    for (i, f) in flows.iter().enumerate() {
        for s in &f.steps {
            m.entry(s.at).or_default().push(i);
        }
    }
    m
}

/// A method may be reached through a value flow cannot trace, so it only counts as unused when its
/// whole class is.
fn method_of_used_class(slices: &[crate::parse::Slice], si: usize, users: &HashMap<SRef, Vec<usize>>, fi: usize) -> bool {
    let Some((class, _)) = slices[si].name.rsplit_once('.') else { return false };
    slices.iter().enumerate().any(|(i, s)| s.name == class && users.contains_key(&(fi, i)))
}

pub fn is_test_file(p: &str) -> bool {
    let file = p.rsplit('/').next().unwrap_or(p);
    p.contains(".test.") || p.contains(".spec.") || p.contains("__tests__/") || p.starts_with("tests/") || p.starts_with("test/") || p.contains("/tests/") || p.contains("/test/") || file.starts_with("test_") || file.ends_with("_test.go") || file.ends_with("_test.py") || file.ends_with("Test.java") || file.ends_with("_spec.rb")
}

pub fn hash_of(repo: &Repo, r: SRef) -> String {
    fnv64(&repo.slice(r).text(&repo.files[r.0]))
}

pub fn render(repo: &Repo, g: &Graph, flows: &[Flow], uids: &crate::ids::Uids, problems: &[String]) -> Lifted {
    let mut files = BTreeMap::new();
    let mut st = Stats { files: repo.files.len(), flows: flows.len(), ..Default::default() };
    let users = used_by(flows);

    for f in flows {
        let mut o = String::from(HEADER);
        writeln!(o, "id: {}", q(&f.id)).unwrap();
        writeln!(o, "uid: {}", q(&f.uid)).unwrap();
        writeln!(o, "kind: {}", q(f.kind)).unwrap();
        writeln!(o, "entry: {}", q(&repo.sid(f.entry))).unwrap();
        match repo.cfg.scenario.iter().find(|s| s.journey.as_deref() == Some(f.id.as_str())) {
            Some(s) => writeln!(o, "scenario: {}", q(&s.name)).unwrap(),
            None => writeln!(o, "verified: false  # no scenario runs this flow yet").unwrap(),
        }
        writeln!(o, "steps:").unwrap();
        for s in &f.steps {
            let sl = repo.slice(s.at);
            writeln!(o, "  - slice: {}", q(&repo.sid(s.at))).unwrap();
            writeln!(o, "    uid: {}", q(uids.step(&repo.sid(s.at)))).unwrap();
            writeln!(o, "    depth: {}", s.depth).unwrap();
            writeln!(o, "    via: {}", q(&s.via)).unwrap();
            writeln!(o, "    lines: {}", q(&ranges(&sl.lines))).unwrap();
            writeln!(o, "    hash: {}", q(&hash_of(repo, s.at))).unwrap();
            if let Some(r) = g.reads.get(&s.at) {
                writeln!(o, "    reads: {}", qlist(&r.iter().cloned().collect::<Vec<_>>())).unwrap();
            }
            if let Some(w) = g.writes.get(&s.at) {
                writeln!(o, "    changes: {}", qlist(&w.iter().cloned().collect::<Vec<_>>())).unwrap();
            }
        }
        if !f.outside.is_empty() {
            writeln!(o, "outside: {}", qlist(&f.outside.iter().cloned().collect::<Vec<_>>())).unwrap();
        }
        if !f.unresolved.is_empty() {
            writeln!(o, "unresolved:").unwrap();
            for (at, u) in &f.unresolved {
                writeln!(o, "  - at: {}", q(&format!("{}:{}", repo.files[at.0].path, u.line + 1))).unwrap();
                writeln!(o, "    code: {}", q(&u.code)).unwrap();
                writeln!(o, "    why: {}", q(&u.why)).unwrap();
            }
        }
        if f.not_followed > 0 {
            writeln!(o, "methods_not_followed: {}", f.not_followed).unwrap();
        }
        files.insert(format!("{}.flow.yaml", f.slug), o);
    }

    let mut sl = String::from(HEADER);
    sl.push_str("# Every slice in the repo, the flows that run it, and the ones no flow reaches.\nfiles:\n");
    let mut lg = String::from(HEADER);
    let mut lg_files = String::new();
    let (mut total, mut placed, mut unplaced_lines, mut unplaced_n) = (0, 0, 0, 0);
    for (fi, f) in repo.files.iter().enumerate() {
        let l = f.ledger();
        total += l.total;
        placed += l.placed;
        unplaced_lines += l.unplaced_lines;
        unplaced_n += l.unplaced_statements;
        st.placed_by_hand += l.by_hand;
        st.lines += l.total;
        if !(l.complete && l.round_trip) {
            st.broken_round_trip.push(f.path.clone());
        }
        if f.parse_error {
            st.parse_errors.push(format!("{}:{}", f.path, ranges(&f.error_lines)));
        }

        writeln!(sl, "  - file: {}", q(&f.path)).unwrap();
        writeln!(sl, "    slices:").unwrap();
        let mut order: Vec<usize> = (0..f.slices.len()).filter(|&i| !f.slices[i].lines.is_empty()).collect();
        order.sort_by_key(|&i| f.slices[i].lines[0]);
        for si in order {
            let s = &f.slices[si];
            st.slices += 1;
            let r = (fi, si);
            writeln!(sl, "      - name: {}", q(&s.name)).unwrap();
            writeln!(sl, "        uid: {}", q(uids.step(&repo.sid(r)))).unwrap();
            writeln!(sl, "        role: {}", q(s.role.label())).unwrap();
            writeln!(sl, "        lines: {}", q(&ranges(&s.lines))).unwrap();
            writeln!(sl, "        hash: {}", q(&hash_of(repo, r))).unwrap();
            if !s.hand.is_empty() {
                writeln!(sl, "        placed_by_hand: {}", q(&ranges(&s.hand))).unwrap();
            }
            let ids: Vec<String> = users.get(&r).map(|v| v.iter().map(|&i| flows[i].id.clone()).collect()).unwrap_or_default();
            if g.on_load.contains(&r) {
                writeln!(sl, "        runs_on_load: true").unwrap();
            }
            if !ids.is_empty() {
                writeln!(sl, "        flows: {}", qlist(&ids)).unwrap();
            } else if si != SUPPORT && s.role.runs() && !g.on_load.contains(&r) && !is_test_file(&f.path) && !method_of_used_class(&f.slices, si, &users, fi) {
                writeln!(sl, "        loose: true  # no flow reaches this").unwrap();
                st.loose.push(repo.sid(r));
            }
        }

        writeln!(lg_files, "  - file: {}", q(&f.path)).unwrap();
        writeln!(lg_files, "    lines: {}", l.total).unwrap();
        writeln!(lg_files, "    placed: {}", l.placed).unwrap();
        if l.by_hand > 0 {
            writeln!(lg_files, "    placed_by_hand: {}", l.by_hand).unwrap();
        }
        writeln!(lg_files, "    unplaced: {}", l.unplaced_lines).unwrap();
        writeln!(lg_files, "    round_trip: {}", l.complete && l.round_trip).unwrap();
        if f.parse_error {
            writeln!(lg_files, "    parse_errors_at: {}", q(&ranges(&f.error_lines))).unwrap();
        }
        if !f.unplaced.is_empty() {
            writeln!(lg_files, "    unplaced_statements:").unwrap();
            for u in &f.unplaced {
                writeln!(lg_files, "      - lines: {}", q(&ranges(&u.lines))).unwrap();
                writeln!(lg_files, "        code: {}", q(&u.text)).unwrap();
                writeln!(lg_files, "        why: {}", q(&u.why)).unwrap();
                st.unplaced.push((f.path.clone(), u.first_line + 1, u.text.clone(), u.why.clone()));
            }
        }
        for (si, s) in f.slices.iter().enumerate() {
            for u in g.unresolved.get(&(fi, si)).cloned().unwrap_or_default() {
                let _ = s;
                st.unresolved.push((f.path.clone(), u.line + 1, u.code, u.why));
            }
        }
    }
    st.unresolved.sort();
    writeln!(lg, "# One owner per line. Placed plus unplaced must equal the total, and the slices must print back to each file byte for byte.").unwrap();
    writeln!(lg, "total_lines: {total}").unwrap();
    writeln!(lg, "placed: {placed}").unwrap();
    writeln!(lg, "placed_by_hand: {}", st.placed_by_hand).unwrap();
    writeln!(lg, "unplaced_lines: {unplaced_lines}").unwrap();
    writeln!(lg, "unplaced_statements: {unplaced_n}").unwrap();
    writeln!(lg, "every_line_has_one_owner: {}", unplaced_n == 0 && st.broken_round_trip.is_empty()).unwrap();
    writeln!(lg, "files:").unwrap();
    lg.push_str(&lg_files);
    files.insert("_slices.yaml".into(), sl);
    files.insert("_ledger.yaml".into(), lg);

    let mut all = String::new();
    for (k, v) in &files {
        all.push_str(k);
        all.push('\0');
        all.push_str(v);
    }
    let fingerprint = fnv64(&all);
    let mut ix = String::from(HEADER);
    writeln!(ix, "version: 2").unwrap();
    writeln!(ix, "fingerprint: {}", q(&fingerprint)).unwrap();
    writeln!(ix, "files: {}", st.files).unwrap();
    writeln!(ix, "lines: {}", st.lines).unwrap();
    writeln!(ix, "slices: {}", st.slices).unwrap();
    writeln!(ix, "flows: {}", flows.len()).unwrap();
    writeln!(ix, "unplaced_statements: {unplaced_n}").unwrap();
    writeln!(ix, "unresolved_calls: {}", st.unresolved.len()).unwrap();
    writeln!(ix, "loose_slices: {}", st.loose.len()).unwrap();
    writeln!(ix, "links_by_name_only: {}", g.guessed_links).unwrap();
    let m = g.method_calls;
    writeln!(ix, "method_calls: {{ followed: {}, packages: {}, built_in: {}, unknown: {} }}", m[0], m[1], m[2], m[3]).unwrap();
    let mut events: Vec<String> = vec![];
    for (evt, hs) in &g.events {
        for h in hs {
            events.push(format!("{evt} -> {}", repo.sid(*h)));
        }
    }
    if !events.is_empty() {
        writeln!(ix, "event_wiring: {}", qlist(&events)).unwrap();
    }
    if !problems.is_empty() {
        writeln!(ix, "config_problems: {}", qlist(problems)).unwrap();
    }
    files.insert("_index.yaml".into(), ix);
    let _ = Role::Data;
    Lifted { files, fingerprint, stats: st }
}
